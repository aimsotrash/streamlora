def idle_to_build(minutes: float = 90.0, seed: int = 7) -> ScenarioSpec:
    """Scenario 1: idle -> sustained compile -> idle."""
    third = minutes * 60.0 / 3.0
    return ScenarioSpec(
        name="idle_to_build", seed=seed,
        description="Idle machine, a sustained parallel build, then idle again.",
        segments=[
            Segment("idle", third, {"cpu.util_pct": 4.0, "proc.cpu_build_pct": 0.0},
                    {"cpu.util_pct": 1.5}, ramp_s=10.0),
            Segment("build", third,
                    {"cpu.util_pct": 82.0, "proc.cpu_build_pct": 620.0,
                     "mem.used_pct": 71.0, "disk.busy_pct": 35.0},
                    {"cpu.util_pct": 6.0, "proc.cpu_build_pct": 60.0}, ramp_s=45.0),
            Segment("idle_after", third,
                    {"cpu.util_pct": 6.0, "proc.cpu_build_pct": 0.0, "mem.used_pct": 52.0,
                     "disk.busy_pct": 1.0},
                    {"cpu.util_pct": 2.0}, ramp_s=60.0),
        ],
    )


def discharge_then_charge(minutes: float = 120.0, seed: int = 11) -> ScenarioSpec:
    """Scenario 2: unplugged discharge under load, then the charger goes in."""
    half = minutes * 60.0 / 2.0
    return ScenarioSpec(
        name="discharge_then_charge", seed=seed, battery_start_pct=78.0,
        description="Discharge under moderate load, then charging.",
        segments=[
            Segment("unplugged", half, {"cpu.util_pct": 38.0, "gpu.util_pct": 12.0},
                    {"cpu.util_pct": 5.0}, ramp_s=20.0, plugged=False),
            Segment("charging", half, {"cpu.util_pct": 30.0, "gpu.util_pct": 8.0},
                    {"cpu.util_pct": 5.0}, ramp_s=20.0, plugged=True),
        ],
    )


def spike_burst(minutes: float = 60.0, seed: int = 13) -> ScenarioSpec:
    """Scenario 3: steady browsing with short violent CPU spikes."""
    segs: list[Segment] = [
        Segment("browse", 600.0, {"cpu.util_pct": 22.0, "net.recv_mbps": 1.2},
                {"cpu.util_pct": 4.0}, ramp_s=20.0)
    ]
    remaining = minutes * 60.0 - 600.0
    while remaining > 0:
        segs.append(
            Segment("spike", 60.0, {"cpu.util_pct": 95.0, "proc.cpu_build_pct": 300.0},
                    {"cpu.util_pct": 4.0}, ramp_s=5.0)
        )
        segs.append(
            Segment("calm", 240.0, {"cpu.util_pct": 20.0, "proc.cpu_build_pct": 0.0},
                    {"cpu.util_pct": 4.0}, ramp_s=15.0)
        )
        remaining -= 300.0
    return ScenarioSpec(
        name="spike_burst", seed=seed, segments=segs,
        description="Interactive baseline punctuated by one-minute full-load spikes.",
    )


def permanent_regime_change(minutes: float = 180.0, seed: int = 17) -> ScenarioSpec:
    """Scenario 4: behaviour changes permanently halfway through.

    The relationship between the drivers and CPU changes, not just the level:
    before the change CPU is browsing-driven and calm; after, the machine is a
    GPU-heavy workstation with a different mean, variance and coupling. A model
    fitted only on the first half is permanently wrong on the second unless it
    adapts, which is exactly what the drift-triggered arm is supposed to fix.
    """
    half = minutes * 60.0 / 2.0
    return ScenarioSpec(
        name="permanent_regime_change", seed=seed,
        description="Light interactive use, then a permanent switch to GPU-heavy work.",
        segments=[
            Segment("before", half,
                    {"cpu.util_pct": 18.0, "gpu.util_pct": 3.0, "mem.used_pct": 44.0,
                     "net.recv_mbps": 0.8},
                    {"cpu.util_pct": 3.0, "gpu.util_pct": 1.0}, ramp_s=20.0),
            Segment("after", half,
                    {"cpu.util_pct": 58.0, "gpu.util_pct": 88.0, "mem.used_pct": 76.0,
                     "net.recv_mbps": 0.2, "disk.busy_pct": 22.0},
                    {"cpu.util_pct": 9.0, "gpu.util_pct": 5.0}, ramp_s=30.0),
        ],
    )


def gappy_idle(minutes: float = 45.0, seed: int = 19) -> ScenarioSpec:
    """Failure-handling scenario: sensor dropouts and a suspend-sized gap."""
    return ScenarioSpec(
        name="gappy_idle", seed=seed,
        description="Idle machine with 20% sample dropout, for gap handling.",
        segments=[
            Segment("clean", minutes * 60.0 / 3, {"cpu.util_pct": 8.0}, {}, ramp_s=10.0),
            Segment("dropouts", minutes * 60.0 / 3, {"cpu.util_pct": 10.0}, {},
                    ramp_s=10.0, dropout=0.2),
            Segment("clean_after", minutes * 60.0 / 3, {"cpu.util_pct": 9.0}, {}, ramp_s=10.0),
        ],
    )


SCENARIOS = {
    "idle_to_build": idle_to_build,
    "discharge_then_charge": discharge_then_charge,
    "spike_burst": spike_burst,
    "permanent_regime_change": permanent_regime_change,
    "gappy_idle": gappy_idle,
}


def build_scenario(name: str, minutes: float | None = None, seed: int | None = None) -> ScenarioSpec:
    if name not in SCENARIOS:
        raise KeyError(f"unknown scenario {name!r}; have {sorted(SCENARIOS)}")
    fn = SCENARIOS[name]
    kwargs: dict[str, float] = {}
    if minutes is not None:
        kwargs["minutes"] = minutes
    if seed is not None:
        kwargs["seed"] = seed
    return fn(**kwargs)  # type: ignore[arg-type]
